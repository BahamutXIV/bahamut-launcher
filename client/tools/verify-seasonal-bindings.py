#!/usr/bin/env python3
"""Check generated seasonal bindings, optionally against the original PE."""

import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "contracts/seasonal-native.json"
GENERATED = ROOT / "src/seasonal_bindings.inc"


def number(value):
    return int(value, 0)


def render(document):
    base = number(document["binary"]["image_base"])
    lines = ["// Generated by client/tools/verify-seasonal-bindings.py; do not edit.",
             "enum class NativeEntry : std::size_t", "{"]
    lines += [f"    {entry['name']}," for entry in document["entries"]]
    lines += ["    Count", "};", "", "inline constexpr std::array<NativeBinding, static_cast<std::size_t>(NativeEntry::Count)> kNativeEntries = {{"]
    for entry in document["entries"]:
        blob = bytes.fromhex(entry["signature"])
        assert 5 <= len(blob) <= 16
        encoded = ", ".join(f"0x{b:02X}" for b in blob)
        lines.append(f"    {{\"{entry['name']}\", 0x{number(entry['va']) - base:08X}u, {{{encoded}}}, {len(blob)}}},")
    lines += ["}};", "", f"inline constexpr std::array<NativeCallSite, {len(document['call_sites'])}> kNativeCallSites = {{{{"]
    for site in document["call_sites"]:
        lines.append(f"    {{0x{number(site['va']) - base:08X}u, 0x{number(site['target']) - base:08X}u}},")
    lines += ["}};", "", f"inline constexpr std::array<NativeCell, {len(document['cells'])}> kNativeCells = {{{{"]
    for cell in document["cells"]:
        lines.append(f"    {{0x{number(cell['va']) - base:08X}u, 0x{number(cell['value']):08X}u}},")
    lines += ["}};", ""]
    return "\n".join(lines)


def check_original(document, path):
    raw = path.read_bytes()
    binary = document["binary"]
    assert len(raw) == binary["bytes"], "original PE size mismatch"
    assert hashlib.sha256(raw).hexdigest() == binary["sha256"], "original PE hash mismatch"
    pe = struct.unpack_from("<I", raw, 0x3C)[0]
    assert raw[pe:pe + 4] == b"PE\0\0"
    count, optional = struct.unpack_from("<H", raw, pe + 6)[0], pe + 24
    assert struct.unpack_from("<H", raw, optional)[0] == 0x10B
    base = struct.unpack_from("<I", raw, optional + 28)[0]
    assert base == number(binary["image_base"])
    table = optional + struct.unpack_from("<H", raw, pe + 20)[0]
    sections = [struct.unpack_from("<8sIIII", raw, table + 40 * i) for i in range(count)]

    def at(va, size):
        rva = number(va) - base if isinstance(va, str) else va - base
        matches = [raw[offset + rva - address:offset + rva - address + size]
                   for _, _, address, length, offset in sections
                   if address <= rva and rva + size <= address + length]
        assert len(matches) == 1 and len(matches[0]) == size, "unmapped original range"
        return matches[0]

    for entry in document["entries"]:
        expected = bytes.fromhex(entry["signature"])
        assert at(entry["va"], len(expected)) == expected, entry["name"]
    for site in document["call_sites"]:
        code = at(site["va"], 5)
        assert code[0] == 0xE8
        assert number(site["va"]) + 5 + struct.unpack_from("<i", code, 1)[0] == number(site["target"])
    for cell in document["cells"]:
        assert struct.unpack("<I", at(cell["va"], 4))[0] == number(cell["value"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate metadata from the tracked manifest")
    parser.add_argument("--exe", type=Path, help="optional original, unpatched retail ffxivgame.exe")
    args = parser.parse_args()
    document = json.loads(MANIFEST.read_text(encoding="ascii"))
    assert document["schema_version"] == 1
    generated = render(document)
    if args.exe:
        check_original(document, args.exe)
        print("PASS original PE identity, entry signatures, caller routes and method cells")
    if args.write:
        GENERATED.write_text(generated, encoding="ascii", newline="\n")
    assert GENERATED.read_text(encoding="ascii") == generated, "seasonal bindings require regeneration"
    print("PASS generated seasonal bindings")


if __name__ == "__main__":
    main()
